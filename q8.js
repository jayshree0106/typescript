"use strict";
function displayproducts(items) {
    return items;
}
console.log(displayproducts(["AC", "TV", "washing machine"]));
console.log(displayproducts([1000, 5000, 5000]));
console.log(displayproducts([1, 3, 5]));
function getFirstElement(items) {
    return items[0];
}
console.log(getFirstElement(["Laptop", "Mobile"]));
console.log(getFirstElement([100, 200]));
console.log(getFirstElement([true, false]));
